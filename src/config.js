// ---------------------------------------------------------------------------

/** @type {Object<string,string>|null} 実行中だけ持っておくスクリプトプロパティ（1回の実行で1度だけ読む） */
let scriptPropertiesCache = null;

/**
 * スクリプトプロパティを読む
 * @param {string} key プロパティ名
 * @return {string|null} 値。未設定ならnull
 */
function getProp(key) {
    if (scriptPropertiesCache === null) {
        scriptPropertiesCache = PropertiesService.getScriptProperties().getProperties();
    }
    return scriptPropertiesCache[key] || null;
}

